/**
 * Normalize semester input to numeric string (e.g. "Sem 1" -> "1", 1 -> "1").
 */
function _normalizeSemToNumberString(sem) {
    if (typeof sem === 'string') {
        const m = sem.match(/\d+/);
        if (m) return String(parseInt(m[0], 10));
    }
    if (typeof sem === 'number') return String(sem);
    return String(sem);
}

/**
 * Return an array of subject names for a given branch and semester.
 * Tries `subjects` first (friendly names), falls back to `subjectCodeMap` keys or `semSubjects` codes.
 */
export function getSubjects(branch, sem) {
    const s = _normalizeSemToNumberString(sem);
    // try subjects (uses numeric keys)
    if (subjects && subjects[branch]) {
        const subjList = subjects[branch][parseInt(s, 10)];
        if (Array.isArray(subjList) && subjList.length) return subjList;
    }
    // try subjectCodeMap (keys are "Sem X")
    const semKey = `Sem ${s}`;
    if (subjectCodeMap && subjectCodeMap[branch] && subjectCodeMap[branch][semKey]) {
        return Object.keys(subjectCodeMap[branch][semKey]);
    }
    // fallback to semSubjects (these are codes) - return codes so caller still gets something
    if (semSubjects && semSubjects[branch] && semSubjects[branch][semKey]) {
        return semSubjects[branch][semKey];
    }
    return [];
}

/**
 * Given branch, semester and a subject name, return the code if available.
 * If subjectCodeMap is present it is used; otherwise attempts to map by index between
 * `subjects` and `semSubjects` when both exist.
 */
export function getSubjectCode(branch, sem, subjectName) {
    const s = _normalizeSemToNumberString(sem);
    const semKey = `Sem ${s}`;
    if (subjectCodeMap && subjectCodeMap[branch] && subjectCodeMap[branch][semKey]) {
        const map = subjectCodeMap[branch][semKey];
        if (map[subjectName]) return map[subjectName];
    }

    // try index mapping between subjects and semSubjects
    if (subjects && subjects[branch] && semSubjects && semSubjects[branch]) {
        const subjList = subjects[branch][parseInt(s, 10)];
        const codeList = semSubjects[branch][semKey];
        if (Array.isArray(subjList) && Array.isArray(codeList) && subjList.length === codeList.length) {
            const idx = subjList.indexOf(subjectName);
            if (idx !== -1) return codeList[idx];
        }
    }

    // if subjectName already looks like a code present in semSubjects, return it
    if (semSubjects && semSubjects[branch] && semSubjects[branch][semKey]) {
        const codeList = semSubjects[branch][semKey];
        if (codeList.includes(subjectName)) return subjectName;
    }

    return null;
}
